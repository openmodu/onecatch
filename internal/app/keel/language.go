// Translate only application-owned labels. Never translate user content.
func uiText(value string) string {
	if locale.Current().Lang == "en" {
		if translated, ok := englishUI[value]; ok {
			return translated
		}
	}
	if value == "文件菜单" {
		return "文件"
	}
	return value
}
func (a *app) setLanguage(value string) {
	a.ui.Preferences.Language = value
	a.ui.Preferences = normalizeUIPreferences(a.ui.Preferences)
	a.applyLanguage()
	a.refreshTrayMenu()
	if a.window != nil {
		a.fail(a.installApplicationMenu())
	}
	a.saveUIPreferences()
	a.ui.SidebarModel = ""
	a.buildMoreMenu()
	a.buildFooterMenu()
	if a.settingsPanel != nil {
		a.settingsPanel.viewModel = ""
	}
}
func (a *app) applyLanguage() {
	if a.ui.Preferences.Language == "en" {
		locale.Apply(locale.English())
	} else {
		locale.Apply(locale.Chinese())
	}
}
func (p *settingsPage) languageSetting() kit.SettingItem {
	return kit.SettingItem{Label: "界面语言", Description: "导航、设置和系统提示使用的语言。任务内容保持原文。", Control: el.ViewFunc(func(cx *el.Context) el.Element {
		selectView := p.selects["language"]
		if selectView == nil {
			selectView = kit.Select("").Appearance(false).Size(32).OnChange(p.app.setLanguage)
			selectView.SetEntries(kit.SelectOption{Value: "zh-CN", Label: "中文"}, kit.SelectOption{Value: "en", Label: "English"})
			p.selects["language"] = selectView
		}
		selectView.SetValue(normalizeUIPreferences(p.app.ui.Preferences).Language)
		return selectView.Render(cx).(*el.DivEl).W(el.Dp(128)).MaxW(el.Full)
	})}
}


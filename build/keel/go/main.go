// Command go uses a local Keel replacement directly. Without that replacement,
// it builds against a private copy of v0.1.8 with reviewed backports.
package main

import (
	"bytes"
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

//go:embed select.patch titlebar.patch
var patchFiles embed.FS

func run() error {
	if len(os.Args) < 2 {
		return fmt.Errorf("usage: go run ./build/keel/go <go arguments>")
	}
	if strings.Contains(os.Getenv("GOFLAGS"), "-modfile") {
		return fmt.Errorf("GOFLAGS already contains -modfile; combine its replacements with the Keel patch explicitly")
	}
	meta, err := exec.Command("go", "list", "-m", "-json", "github.com/dyike/keel").Output()
	if err != nil {
		return fmt.Errorf("locate Keel: %w", err)
	}
	var module struct {
		Dir, Version string
		Replace      *struct{ Path, Dir, Version string }
	}
	if err := json.Unmarshal(meta, &module); err != nil {
		return err
	}
	if module.Replace != nil && module.Replace.Dir != "" && module.Replace.Version == "" {
		// Local development uses the checkout directly, including edits made
		// while the watcher is running. Do not replace it with a cached patch.
		command := exec.Command("go", os.Args[1:]...)
		command.Env = append(os.Environ(), "ONECATCH_KEEL_SELECT_PATCH=1")
		command.Stdin, command.Stdout, command.Stderr = os.Stdin, os.Stdout, os.Stderr
		return command.Run()
	}
	if module.Version != "v0.1.8" || module.Replace != nil {
		return fmt.Errorf("Keel patches require unmodified v0.1.8; review the patches before changing the dependency")
	}
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	var patches []byte
	for _, name := range []string{"select.patch", "titlebar.patch"} {
		data, err := patchFiles.ReadFile(name)
		if err != nil {
			return err
		}
		patches = append(patches, data...)
	}
	hash := sha256.Sum256(patches)
	cache := filepath.Join(root, "bin", "keel-patches")
	patched := filepath.Join(cache, "keel-v0.1.8-"+hex.EncodeToString(hash[:8]))
	if _, err := os.Stat(filepath.Join(patched, ".onecatch-keel-fixed")); err != nil {
		if err := os.MkdirAll(cache, 0755); err != nil {
			return err
		}
		staging, err := os.MkdirTemp(cache, ".staging-")
		if err != nil {
			return err
		}
		defer os.RemoveAll(staging)
		if err := copyModule(module.Dir, staging); err != nil {
			return err
		}
		patch := exec.Command("git", "apply", "--whitespace=error", "-")
		patch.Dir, patch.Stdin = staging, bytes.NewReader(patches)
		patch.Env = append(os.Environ(), "GIT_CEILING_DIRECTORIES="+cache)
		if output, err := patch.CombinedOutput(); err != nil {
			return fmt.Errorf("Keel patches no longer apply: %w\n%s", err, output)
		}
		for _, file := range []string{"ui/kit/select.go", "ui/window/titlebar_darwin.go"} {
			before, err := os.ReadFile(filepath.Join(module.Dir, file))
			if err != nil {
				return err
			}
			after, err := os.ReadFile(filepath.Join(staging, file))
			if err != nil {
				return err
			}
			if bytes.Equal(before, after) {
				return fmt.Errorf("Keel patch for %s was skipped; refusing an unpatched build", file)
			}
		}
		if err := os.WriteFile(filepath.Join(staging, ".onecatch-keel-fixed"), hash[:], 0644); err != nil {
			return err
		}
		// Discard only a previous incomplete copy generated by this bridge.
		if _, err := os.Stat(filepath.Join(patched, ".onecatch-keel-fixed")); os.IsNotExist(err) {
			if err := os.RemoveAll(patched); err != nil {
				return err
			}
		}
		if err := os.Rename(staging, patched); err != nil {
			// A concurrent build may have already installed the same immutable copy.
			if _, statErr := os.Stat(filepath.Join(patched, "go.mod")); statErr != nil {
				return err
			}
		}
	}
	dir, err := os.MkdirTemp(cache, ".modfile-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	mod, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return err
	}
	mod = append(mod, []byte(fmt.Sprintf("\nreplace github.com/dyike/keel => %q\n", filepath.ToSlash(patched)))...)
	path := filepath.Join(dir, "onecatch.mod")
	if err := os.WriteFile(path, mod, 0644); err != nil {
		return err
	}
	if sum, err := os.ReadFile(filepath.Join(root, "go.sum")); err == nil {
		if err := os.WriteFile(filepath.Join(dir, "onecatch.sum"), sum, 0644); err != nil {
			return err
		}
	} else {
		return err
	}
	args := os.Args[1:]
	env := append(os.Environ(), "ONECATCH_KEEL_SELECT_PATCH=1")
	if args[0] == "tool" {
		// Keel invokes another Go build. Preserve the replacement there, and
		// give the launched app the original environment to restore at startup.
		env = append(env, "ONECATCH_KEEL_GOFLAGS_BEFORE="+os.Getenv("GOFLAGS"), "GOFLAGS="+strings.TrimSpace(os.Getenv("GOFLAGS")+" "+fmt.Sprintf("%q", "-modfile="+path)))
	} else {
		// A CLI flag changes this build without leaking into tests, Agent
		// commands or gopls subprocesses that work in other modules.
		switch args[0] {
		case "build", "run", "test", "vet", "list":
			args = append([]string{args[0], "-modfile=" + path}, args[1:]...)
		default:
			return fmt.Errorf("unsupported patched Go command: %s", args[0])
		}
	}
	command := exec.Command("go", args...)
	command.Env = env
	command.Stdin, command.Stdout, command.Stderr = os.Stdin, os.Stdout, os.Stderr
	return command.Run()
}

func copyModule(source, destination string) error {
	return filepath.WalkDir(source, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		rel, err := filepath.Rel(source, path)
		if err != nil {
			return err
		}
		target := filepath.Join(destination, rel)
		if entry.IsDir() {
			return os.MkdirAll(target, 0755)
		}
		if !entry.Type().IsRegular() {
			return fmt.Errorf("unexpected non-regular dependency file: %s", path)
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, data, 0644)
	})
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		if exit, ok := err.(*exec.ExitError); ok {
			os.Exit(exit.ExitCode())
		}
		os.Exit(1)
	}
}

function storedLanguage() {
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY);
  } catch {
    return null;
  }
}

export function normalizeLanguage(value) {
  return String(value || "").toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

const initialLanguage = supportedLanguages.includes(storedLanguage())
  ? storedLanguage()
  : normalizeLanguage(typeof navigator === "undefined" ? "en" : navigator.language);

i18n.use(initReactI18next).init({
  resources: { "zh-CN": { translation: zh }, en: { translation: en } },
  lng: initialLanguage,
  fallbackLng: "en",
  supportedLngs: supportedLanguages,
  interpolation: { escapeValue: false },
  initImmediate: false,
});

function applyLanguage(language) {
  const normalized = normalizeLanguage(language);
  if (typeof document !== "undefined") document.documentElement.lang = normalized;
  try { localStorage.setItem(LANGUAGE_STORAGE_KEY, normalized); } catch { /* best effort */ }
}

applyLanguage(initialLanguage);
i18n.on("languageChanged", applyLanguage);

export const translationResources = { "zh-CN": zh, en };
export default i18n;
